BY_ID = {t["id"]: t for t in TOPICS + [GENERIC]}


def detect(text: str):
    """가장 많이 언급된 주제를 고른다. 반환: (주제 dict, 점수표)."""
    scores = {}
    for t in TOPICS:
        n = sum(text.count(k) for k in t["keywords"])
        if n:
            scores[t["id"]] = n
    if not scores:
        return GENERIC, scores
    return BY_ID[max(scores, key=scores.get)], scores


def matched_points(topic: dict, text: str):
    """글에 나온 세부 키워드에 해당하는 혹할 포인트 [(라벨, 문장)]."""
    return [v for keys, v in topic["points"].items() if any(k in text for k in keys)]


